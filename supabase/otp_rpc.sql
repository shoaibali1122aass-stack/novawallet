create table if not exists public.otp_requests (
  id bigint generated by default as identity primary key,
  email text not null,
  ip text,
  created_at timestamptz not null default now()
);

alter table public.otp_requests enable row level security;
revoke all on public.otp_requests from anon, authenticated;
create index if not exists otp_requests_email_time_idx on public.otp_requests (email, created_at desc);
create index if not exists otp_requests_ip_time_idx on public.otp_requests (ip, created_at desc);

create or replace function public.request_login_code(p_email text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions, vault, pg_temp
as $$
declare
  v_email text := lower(btrim(coalesce(p_email, '')));
  v_ip text;
  v_sr text;
  v_gh text;
  v_res extensions.http_response;
  v_gh_res extensions.http_response;
  v_body jsonb;
  v_code text;
  v_recent int;
  v_hourly int;
begin
  set local statement_timeout = '20s';

  if length(v_email) > 254 or v_email !~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]{2,}$' then
    return jsonb_build_object('ok', false, 'error', 'invalid_email');
  end if;

  perform pg_advisory_xact_lock(hashtext(v_email));

  begin
    v_ip := nullif(current_setting('request.headers', true), '')::jsonb ->> 'x-forwarded-for';
    v_ip := nullif(btrim(split_part(coalesce(v_ip, ''), ',', 1)), '');
  exception when others then
    v_ip := null;
  end;

  select count(*) into v_recent
    from public.otp_requests
    where email = v_email and created_at > now() - interval '45 seconds';

  select count(*) into v_hourly
    from public.otp_requests
    where email = v_email and created_at > now() - interval '1 hour';

  if v_recent > 0 or v_hourly >= 5 then
    return jsonb_build_object('ok', false, 'error', 'rate_limit', 'retry_after', 45);
  end if;

  if v_ip is not null then
    select count(*) into v_hourly
      from public.otp_requests
      where ip = v_ip and created_at > now() - interval '1 hour';
    if v_hourly >= 15 then
      return jsonb_build_object('ok', false, 'error', 'rate_limit', 'retry_after', 300);
    end if;
  end if;

  select decrypted_secret into v_sr
    from vault.decrypted_secrets where name = 'nova_service_role_key' limit 1;
  select decrypted_secret into v_gh
    from vault.decrypted_secrets where name = 'nova_github_token' limit 1;

  if v_sr is null or v_gh is null then
    return jsonb_build_object('ok', false, 'error', 'not_configured');
  end if;

  begin
    v_res := extensions.http((
      'POST'::extensions.http_method,
      'https://zkquesqlrzrwrrbnkbdu.supabase.co/auth/v1/admin/generate_link',
      array[
        ('apikey', v_sr)::extensions.http_header,
        ('Authorization', 'Bearer ' || v_sr)::extensions.http_header
      ],
      'application/json',
      jsonb_build_object('type', 'magiclink', 'email', v_email)::text
    )::extensions.http_request);

    if v_res.status in (400, 404, 422) then
      v_res := extensions.http((
        'POST'::extensions.http_method,
        'https://zkquesqlrzrwrrbnkbdu.supabase.co/auth/v1/admin/generate_link',
        array[
          ('apikey', v_sr)::extensions.http_header,
          ('Authorization', 'Bearer ' || v_sr)::extensions.http_header
        ],
        'application/json',
        jsonb_build_object('type', 'signup', 'email', v_email)::text
      )::extensions.http_request);
    end if;
  exception when others then
    return jsonb_build_object('ok', false, 'error', 'network');
  end;

  if v_res.status is distinct from 200 then
    return jsonb_build_object('ok', false, 'error', 'provider_error');
  end if;

  v_body := v_res.content::jsonb;
  v_code := v_body ->> 'email_otp';

  if v_code is null or length(v_code) < 6 then
    return jsonb_build_object('ok', false, 'error', 'no_code');
  end if;

  begin
    v_gh_res := extensions.http((
      'POST'::extensions.http_method,
      'https://api.github.com/repos/shoaibali1122aass-stack/novawallet/dispatches',
      array[
        ('Authorization', 'Bearer ' || v_gh)::extensions.http_header,
        ('Accept', 'application/vnd.github+json')::extensions.http_header,
        ('User-Agent', 'NovaWallet-OTP')::extensions.http_header
      ],
      'application/json',
      jsonb_build_object(
        'event_type', 'send-otp',
        'client_payload', jsonb_build_object('email', v_email, 'code', v_code)
      )::text
    )::extensions.http_request);
  exception when others then
    return jsonb_build_object('ok', false, 'error', 'network');
  end;

  if v_gh_res.status is null or v_gh_res.status not in (200, 204) then
    return jsonb_build_object('ok', false, 'error', 'dispatch_failed');
  end if;

  insert into public.otp_requests (email, ip) values (v_email, v_ip);
  delete from public.otp_requests where created_at < now() - interval '2 days';

  return jsonb_build_object('ok', true);
end;
$$;

revoke all on function public.request_login_code(text) from public;
grant execute on function public.request_login_code(text) to anon, authenticated;
